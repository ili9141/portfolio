"""Tokenize the site's titles with Qwen3's real tokenizer -> src/content/tokens.ts.

The token boxes on the big titles show how an LLM actually splits them, so the
pieces and ids must come from a real tokenizer, not be made up. Re-run this
whenever a title in src/content/site.ts changes:

    pip install tokenizers
    python scripts/tokenize-titles.py

It picks up every `title: "..."` in site.ts (both languages), plus the hero
name. A title missing from tokens.ts still renders, just without token boxes.
"""

import json
import re
import urllib.request
from pathlib import Path

from tokenizers import Tokenizer

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "src" / "content" / "site.ts"
OUT = ROOT / "src" / "content" / "tokens.ts"
CACHE = ROOT / "scripts" / ".cache" / "qwen3-tokenizer.json"
TOKENIZER_URL = "https://huggingface.co/Qwen/Qwen3-8B/resolve/main/tokenizer.json"
EXTRA = ["Ilias Ait Barrehil"]


def load_tokenizer() -> Tokenizer:
    if not CACHE.exists():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(TOKENIZER_URL, CACHE)
    return Tokenizer.from_file(str(CACHE))


def main() -> None:
    tok = load_tokenizer()
    titles = sorted(set(re.findall(r'title:\s*"([^"]+)"', SITE.read_text(encoding="utf-8"))) | set(EXTRA))
    table: dict[str, list[list]] = {}
    for title in titles:
        enc = tok.encode(title)
        pieces = [[title[a:b], i] for (a, b), i in zip(enc.offsets, enc.ids)]
        # A byte-level BPE can split one accented character across two tokens;
        # both then report the same character span. Refuse rather than render
        # a garbled piece — such a title needs a hand-checked merge.
        if "".join(p for p, _ in pieces) != title:
            raise SystemExit(f"pieces do not rebuild {title!r}: {pieces}")
        table[title] = pieces

    # One line per title keeps the file readable and its diffs small.
    lines = [f"  {json.dumps(t, ensure_ascii=False)}: {json.dumps(p, ensure_ascii=False)}," for t, p in table.items()]
    body = "{\n" + "\n".join(lines) + "\n}"
    OUT.write_text(
        "// Generated by scripts/tokenize-titles.py from Qwen/Qwen3-8B's tokenizer.json.\n"
        "// Do not edit by hand: change the title in site.ts and re-run the script.\n"
        "// Each entry is [piece, id]; a leading space belongs to the piece, as in the tokenizer.\n\n"
        "export type Token = [piece: string, id: number];\n\n"
        f"export const TOKENS: Record<string, Token[]> = {body};\n",
        encoding="utf-8",
    )
    print(f"{len(table)} titles -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
